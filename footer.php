        function sendMessage() {
            var inputField = document.getElementById('chat-input');
            var message = inputField.value.trim();
            if (message === '') return;

            var chatBody = document.getElementById('chat-body');
            
            // In tin nhắn khách
            chatBody.innerHTML += '<div class="user-msg">' + message + '</div>';
            inputField.value = '';
            chatBody.scrollTop = chatBody.scrollHeight;

            // Hiệu ứng Bot đang soạn tin
            var typingId = 'typing-' + Date.now();
            chatBody.innerHTML += '<div class="bot-msg" id="' + typingId + '"><i><i class="fas fa-spinner fa-spin me-1"></i> Trợ lý AI đang tư vấn...</i></div>';
            chatBody.scrollTop = chatBody.scrollHeight;

            var formData = new FormData();
            formData.append('tin_nhan', message);

            fetch('xuly_bot.php', {
                method: 'POST',
                body: formData
            })
            .then(response => response.text())
            .then(data => {
                var typingElem = document.getElementById(typingId);
                if (typingElem) typingElem.remove();
                chatBody.innerHTML += '<div class="bot-msg">' + data + '</div>';
                chatBody.scrollTop = chatBody.scrollHeight;
            })
            .catch(err => {
                var typingElem = document.getElementById(typingId);
                if (typingElem) typingElem.remove();
                chatBody.innerHTML += '<div class="bot-msg">Dạ kết nối tạm thời bị gián đoạn. Bạn vui lòng thử lại sau giây lát nhé!</div>';
                chatBody.scrollTop = chatBody.scrollHeight;
            });
        }

        document.getElementById('send-chat').addEventListener('click', sendMessage);
        document.getElementById('chat-input').addEventListener('keypress', function(e) {
            if (e.key === 'Enter') sendMessage();
        });

